import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
const cache = new Map();
function moduleURL(file) {
    file = path.resolve(file);
    if (cache.has(file)) return cache.get(file);
    const source = fs.readFileSync(file, 'utf8').replace(/from (['"])(\.\/[^'"]+)\1/g,
        (_, quote, dependency) => `from ${JSON.stringify(moduleURL(path.resolve(path.dirname(file), dependency)))}`);
    const result = 'data:text/javascript;base64,' + Buffer.from(source).toString('base64');
    cache.set(file, result);
    return result;
}
const {default: Inventory} = await import(moduleURL('inventory.js'));
const {default: StackInteraction, minerStore} = await import(moduleURL('stackInteraction.js'));
const {default: Miner} = await import(moduleURL('miner.js'));
const {workerTiers, minerUpgrades} = await import(moduleURL('gameData.js'));
const inventory = new Inventory();
const interaction = new StackInteraction(inventory);
const miner = new Miner(workerTiers[0]);
const store = minerStore(miner);
miner.storage.Stone = 200;
interaction.click(store, 'Stone', true);
assert.deepEqual(interaction.held, {type:'Stone',count:1});
assert.equal(miner.storage.Stone,199);
interaction.click(interaction.playerStore, 0);
assert.equal(interaction.held,null);
assert.equal(inventory.slots[0].count,1);
interaction.click(store,'Stone');
assert.equal(interaction.held.count,199);
interaction.click(interaction.playerStore,0);
assert.equal(inventory.slots[0].count,200);
assert.equal(interaction.held,null);
interaction.quickTransfer(interaction.playerStore,0,store);
assert.equal(miner.storage.Stone,0);
assert.equal(inventory.slots[0].count,200);
interaction.click(interaction.playerStore,0);
interaction.click(store,'Stone');
interaction.click(store,'Stone',true);
assert.equal(miner.storage.Stone,0);
assert.equal(interaction.held.count,200);
interaction.cancel();
assert.equal(inventory.slots[0].count,200);
miner.storage.Stone=1000;
interaction.quickTransfer(store,'Stone');
assert.equal(inventory.slots[0].count,1200);
assert.equal(miner.storage.Stone,0);
// A full inventory can merge matching materials but cannot accept a new type.
inventory.slots=Array.from({length:20},()=>({type:'Stone',count:1000}));
miner.storage.Gold=100;
interaction.quickTransfer(store,'Gold');
assert.equal(miner.storage.Gold,100);
interaction.click(store,'Gold');
interaction.click(interaction.playerStore,0);
assert.equal(interaction.held.type,'Stone');
interaction.cancel();
assert.equal(miner.storage.Gold,100);
assert.equal(inventory.slots[0].type,'Stone');
for (const tier of workerTiers) {
 const worker = new Miner(tier);
 assert.equal(worker.upgradeCost('resources'),Math.ceil(tier.cost*.25));
 assert.equal(worker.upgradeCost('cycle'),Math.ceil(tier.cost*.30));
}
const wallet={balance:0};
assert.equal(miner.buyUpgrade('cycle',wallet),false);
assert.equal(miner.cycleLevel,1);
wallet.balance=10000;
const cost=miner.upgradeCost('cycle');
assert.equal(miner.buyUpgrade('cycle',wallet),true);
assert.equal(wallet.balance,10000-cost);
assert.equal(miner.cycleLevel,2);
miner.resourceLevel=minerUpgrades.maxLevel;
assert.equal(miner.upgradeCost('resources'),null);
const balance=wallet.balance;
assert.equal(miner.buyUpgrade('resources',wallet),false);
assert.equal(wallet.balance,balance);
console.log('Passed pickup, one-item clicks, merging, swapping, rollback, quick transfers, capacity, upgrade payment and level caps.');

// Multiple workers share one output; rolling back a held stack preserves live production.
const shared = {storage:{},produced:{}};
const first = new Miner(workerTiers[0],shared);
const second = new Miner(workerTiers[1],shared);
const sharedInventory = new Inventory();
const sharedInteraction = new StackInteraction(sharedInventory);
const sharedStore = minerStore(shared);
first.mine(); second.mine();
assert.equal(first.storage,second.storage);
const beforeProduction = Object.values(shared.storage).reduce((sum,n)=>sum+n,0);
const type = Object.keys(shared.storage)[0];
sharedInteraction.click(sharedStore,type,true);
first.mine(); second.mine();
const newlyProduced = Object.values(shared.produced).reduce((sum,n)=>sum+n,0) - beforeProduction;
sharedInteraction.cancel();
assert.equal(Object.values(shared.storage).reduce((sum,n)=>sum+n,0),beforeProduction+newlyProduced);
assert.equal(first.storage,shared.storage);
assert.equal(second.storage,shared.storage);
const previousElapsed = first.elapsed;
first.update(first.cycleSeconds / 2);
assert.ok(first.elapsed > previousElapsed);
console.log('Passed shared output, active production during transfers, safe cancellation, and countdown progression.');
